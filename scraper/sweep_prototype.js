const WANTED = ARGS.filter(a => !a.startsWith('--'));

// How many venues run at once. ACROSS venues only — never several pages within
// one venue, which is the hammering case IR-15 rejects at any scale. Each venue
// still visits its own pages strictly one at a time, so no museum sees more
// than one request from us at a time no matter what this is set to.
//
// Default 4: a 21-venue serial run projects to ~20 minutes, and step 4 of the
// work order is a repeated re-run loop where that hurts. Raising it does not
// increase load on any single venue; it increases the number of DIFFERENT
// venues in flight, and the ceiling is this container's memory, since each
// worker holds its own browser context.
const JOBS_ARG = ARGS.find(a => a.startsWith('--jobs='));
const CONCURRENCY = Math.max(1, Math.min(8, parseInt(JOBS_ARG?.split('=')[1] ?? '4', 10) || 4));

// DEF-04, the hang bound. A BLOCKED venue costs about a second — the site
// refuses and we move on. A HANGING one costs NAV_TIMEOUT plus a retry on every
// page it has, so a venue with 40 pages could hold a run for 25 minutes on its
// own while returning nothing.
//
// A venue that exceeds this is abandoned, NOT written, and picked up by the
// next --continue. That is the same outcome as any other incomplete venue, and
// it relies on the same guarantee: a file on disk means that venue finished.
// Overridable with --budget-mins=N so the abandon path can actually be
// exercised. A guard nobody has ever seen fire is a guard nobody knows works:
// this one was proved with --budget-mins=0.05 against a live venue before it
// was trusted at ten minutes.
const BUDGET_ARG = ARGS.find(a => a.startsWith('--budget-mins='));
const VENUE_BUDGET_MS = Math.max(
  1000,
  Math.round((parseFloat(BUDGET_ARG?.split('=')[1] ?? '10') || 10) * 60 * 1000),
);

// Her clock, not the server's. Fixed to her zone rather than the machine's, so
// a run from this container and a run from her laptop stamp the same way and
// sort together — otherwise a 6pm Sydney run files itself as 08:00, on what can
// be the wrong date either side of midnight.
const RUN_TZ = 'Australia/Sydney';
function runStamp(d = new Date()) {
  const p = new Intl.DateTimeFormat('en-CA', {
    timeZone: RUN_TZ, hourCycle: 'h23',
    year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
  }).formatToParts(d).reduce((o, x) => (o[x.type] = x.value, o), {});
  return `${p.year}-${p.month}-${p.day}_${p.hour}${p.minute}${p.second}`;
}

function newestRunDir() {
  try {
    const dirs = fs.readdirSync(OUT_DIR)
      .filter(n => /^run_/.test(n) && fs.statSync(path.join(OUT_DIR, n)).isDirectory())
      .sort();
    return dirs.length ? path.join(OUT_DIR, dirs[dirs.length - 1]) : null;
  } catch { return null; }
}

// --continue resumes the newest run directory; anything else starts a new one.
const RUN_DIR = (CONTINUE && newestRunDir()) || path.join(OUT_DIR, `run_${runStamp()}`);
const CSV_PATH = path.join(RUN_DIR, 'sweep.csv');
const LOG_PATH = path.join(RUN_DIR, `log_${runStamp()}.txt`);

const venueCsvPath = code => path.join(RUN_DIR, `${code}.csv`);
const venueIsDone = code => fs.existsSync(venueCsvPath(code));

// Venues this invocation will actually scrape. Naming venues always wins; a
// bare --continue means "finish this run", which is exactly the venues with no
// file yet. No stored state, no staleness, nothing to get wrong.
function venuesForThisRun() {
  const asked = WANTED.length ? VENUE_ORDER.filter(c => WANTED.includes(c)) : VENUE_ORDER;
  return (CONTINUE && !WANTED.length) ? asked.filter(c => !venueIsDone(c)) : asked;
}

const LOOKBACK = new Date('2024-07-01');

/**
 * Expand a venue's year-filtered archive into one page per year.
 *
 * Some archives serve ONE YEAR PER ADDRESS — the Met's is
 * `/exhibitions/past?year=2025`. Those years must NOT be written into a recipe
 * by hand. A hardcoded list is correct on the day it is typed and silently
 * wrong afterwards: run this in 2028 with `2025, 2024` in the file and the
 * sweep completes, reports no error, and is simply missing two years. Nothing
 * in the coverage table can show a page that was never requested.
 *
 * So the years are DERIVED, which is code's job — there is exactly one correct
 * answer and it follows from the inputs (Section 1 of the project guide).
 *
 *   from  the lookback floor's year, because a show open across the floor is
 *         filed under the year it CLOSES, so that year is the oldest that can
 *         hold a keeper
 *   to    last year, NOT this one: the venue's bare `past` page already serves
 *         the current year, and requesting it twice costs a page load and
 *         stamps "Also listed on the venue's 'past 2026' page." onto her
 *         approval cards — one page recorded twice, which is the exact
 *         misleading note the dead `yearDropdown` used to produce
 *
 * Newest first, so the years she is most likely to care about are read first
 * if a run is cut short.
 */
function expandYearArchive(entry, floor = LOOKBACK, today = new Date()) {
  const first = floor.getUTCFullYear();
  // THE CURRENT YEAR IS NORMALLY EXCLUDED, because a venue's bare "past" page
  // already serves it, and asking twice stamps "Also listed on the venue's
  // 'past 2026' page." onto her approval cards.
  //
  // The Art Institute has NO bare past page — its archive is nothing but year
  // addresses, and her screenshot shows year=2026 holding 11 exhibitions. So a
  // venue whose archive is year-only opts in, and the current year becomes
  // another page rather than a duplicate of one.
  const last = today.getUTCFullYear() - (entry.includeCurrentYear ? 0 : 1);
  const pages = [];
  for (let y = last; y >= first; y--) {
    // Two shapes of the same thing. Most venues filter with a query parameter
    // (the Met, the Louvre); the Uffizi puts the year in the PATH instead,
    // /en/event-category/exhibitions/years/2026. Both are server-side, so both
    // are simply another address, and either way the years are DERIVED here
    // rather than written into a recipe — a hand-typed list is right the day it
    // is typed and quietly wrong every year after.
    // `suffix` carries a SECOND filter that sits after the year — the Art
    // Institute's archive paginates inside each year as well as by year
    // ("Showing 20 out of 25 Exhibitions"), and both are ordinary query
    // parameters, so page 2 of a year is simply another address.
    const path = entry.param
      ? `${entry.path}?${entry.param}=${y}${entry.suffix || ''}`
      : `${entry.path}${entry.yearPath}${y}${entry.suffix || ''}`;
    pages.push({ path, ctx: `${entry.ctx} ${y}` });
  }
  return pages;
}

/**
 * Follow a numbered archive onto its next page, if there is one.
 *
 * THE MENIL'S PAST ARCHIVE IS PAGINATED and only its first page was being read:
 * 11 exhibitions on `/exhibitions/past` and 12 more on `?page=1`, all 12 lost.
 * Her count caught it; nothing in the output could have, because a first page
 * that reads perfectly looks exactly like a complete archive.
 *
 * WHY THE PAGES ARE NOT WRITTEN INTO THE RECIPE. This is the same trap as the
 * year archive, one step worse. A recipe saying "past has 2 pages" is correct
 * the afternoon it is typed and wrong the moment the venue closes one more
 * show: the sweep completes, reports no error, and is missing a page. But
 * unlike years, the count cannot be derived up front either — only the site
 * knows how deep its archive goes. So it is derived AT RUN TIME by asking:
 * the loop requests the next page, and the site's answer decides whether there
 * is another.
 *
 * THE STOP RULE IS "THIS PAGE ADDED NO NEW EXHIBITION ADDRESS". Both ways an
 * archive can end are the same answer:
 *   - the page is empty, or 404s, or serves a bare "no results" shell
 *   - the site CLAMPS an over-large page number back to the last real page, so
 *     every address on it has already been seen and the URL-identity guard
 *     collects none of them
 *
 * IT ALSO STOPS AT THE LOOKBACK FLOOR, and that is not an optimisation — it is
 * the difference between the fix working and the fix making things worse.
 *
 * The first version walked every archive page to the true end, on the grounds
 * that stopping at the floor assumes the archive is sorted newest-first and a
 * venue might one day re-sort. What that caution actually bought at the Menil:
 * eleven pages instead of three, ninety seconds of extra page loads per sweep,
 * and THIRTEEN rows of rubbish on her approval pile — decades-old exhibitions
 * the venue publishes no dates for, which nothing downstream could drop because
 * an unknown date is never evidence of being too old. The guard against a
 * hypothetical re-sort created a certain mess.
 *
 * THE ORDERING IS NOT ASSUMED, IT IS CHECKED. Every page carries the closing
 * date of its newest exhibition to the next one. While each page is older than
 * the one before it, the archive is demonstrably in descending date order and
 * "nothing here reaches the floor" really does mean "nothing after here can
 * either". The first page that breaks that pattern says so in the log and the
 * walk reverts to reading to the end for the rest of that venue. So the
 * hypothetical is handled by noticing it, not by paying for it every sweep.
 *
 * A page with no readable dates at all proves nothing either way, so the walk
 * simply carries on past it.
 *
 * MAX_ARCHIVE_PAGES IS A RUNAWAY GUARD, NOT THE STOP. A site that serves a
 * plausible page for any number at all would otherwise loop forever. Reaching
 * it means the real stop never fired, which is a defect in this function or a
 * change at the venue — so it leaves a marker row on her approval pile rather
 * than trimming the venue and saying nothing.
 *
 * A venue opts in by putting `paginate` on the PAGE, not the venue: the Menil
 * paginates its past archive and neither of its other two listings.
 *
 *   paginate: { param: 'page', from: 1 }   ->  ?page=1, ?page=2, ...
 *
 * `from` is the number of the page AFTER the bare address, because sites
 * disagree about whether the first page is 0 or 1 and only the site can say.
 * The Menil's bare /exhibitions/past is page 0, so its second page is ?page=1.
 */
function followPagination(queue, pg, newRows, rows, code, v) {
  const spec = pg.paginate;
  if (!spec) return;

  // The site has told us there is nothing after this page.
  if (newRows.length === 0) {
    if (pg.discovered) log(`  PAGINATION end: ${pg.ctx} added no new exhibitions`);
    return;
  }

  // STOP AT THE LOOKBACK FLOOR. See the note above on why this is evidence
  // rather than an assumption.
  const floorDate = v.lookbackFrom ? new Date(v.lookbackFrom) : LOOKBACK;
  const floor = floorDate.toISOString().slice(0, 10);
  // DATED ROWS ONLY. afterLookback() deliberately keeps an undated row, which
  // is right when deciding a ROW's fate and wrong when deciding where we are in
  // the archive: one undated straggler on an otherwise 2019 page would restart
  // the walk and drag the whole archive back in. What places a page is the
  // dates it does publish.
  const ends = newRows.map(r => r.end_date).filter(Boolean).sort();
  const newest = ends[ends.length - 1];
  if (newest) {
    // THE ORDERING CHECK. Each page must be older than the one before it. While
    // that holds, the archive is demonstrably in descending date order and the
    // floor rule below is sound. The first time it does not hold, the venue has
    // re-sorted or mixed its archive, the rule loses its footing, and the walk
    // reverts to reading every page to the end — slow, and correct, which is
    // the right way round.
    if (pg.prevNewest && newest > pg.prevNewest) {
      log(`  PAGINATION: ${pg.ctx} is NEWER than the page before it (${newest} > ${pg.prevNewest}) — archive is not in date order, reading it all`);
      pg.unordered = true;
    }
    const ordered = !(pg.unordered);
    if (ordered && new Date(newest + 'T00:00:00') < floorDate) {
      log(`  PAGINATION end: ${pg.ctx} — its newest exhibition closed ${newest}, before the ${floor} floor, so every later page is older still`);
      return;
    }
  }

  const next = (pg.pageNum === undefined ? spec.from : pg.pageNum + 1);
  const count = queue.filter(q => q.paginate === spec).length;
  if (count >= MAX_ARCHIVE_PAGES) {
    log(`  PAGINATION RUNAWAY ${pg.ctx}: hit the ${MAX_ARCHIVE_PAGES}-page guard`);
    rows.push({
      venue_code: code, title: `[${pg.ctx} page]`, start_date: '', end_date: '',
      summary: '', url: v.base + pg.path,
      notes: `The venue's "${pg.ctx}" archive was still returning new exhibitions after ${MAX_ARCHIVE_PAGES} pages, so reading it was stopped. Older exhibitions may be missing. Marker row, not an exhibition.`,
    });
    return;
  }

  // BUILD FROM THE BARE ADDRESS, never from the page we are standing on.
  // Appending to the current path gives `?page=1&page=2` on the second hop —
  // which most sites answer with page 1 again, so the URL guard finds every
  // address already seen, the stop rule fires, and the archive silently ends
  // one page in. The bare address is carried along for exactly this reason.
  const basePath = pg.basePath || pg.path;
  const sep = basePath.includes('?') ? '&' : '?';
  queue.push({
    path: `${basePath}${sep}${spec.param}=${next}`,
    ctx: `${pg.ctx.replace(/ p\d+$/, '')} p${next}`,
    basePath,
    paginate: spec,
    pageNum: next,
    // Carried so the next page can check it is older than this one, and so a
    // venue once found to be out of order stays that way for the rest of the
    // walk rather than re-deciding page by page.
    prevNewest: newest || pg.prevNewest,
    unordered: !!pg.unordered,
    // Marks this page as one the loop asked for rather than one the recipe
    // named, which is what suppresses the "loaded but nothing matched" marker
    // when the archive ends.
    discovered: true,
  });
}

/** A venue's pages, with any year-filtered archive expanded to real years. */
function listingPages(v) {
  const floor = v.lookbackFrom ? new Date(v.lookbackFrom) : LOOKBACK;
  return v.pages.flatMap(pg => pg.yearArchive ? expandYearArchive(pg, floor) : [pg]);
}

