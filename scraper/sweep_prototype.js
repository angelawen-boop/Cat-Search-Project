// NO USER-AGENT IS SET. Chromium states what it actually is, and that is the
// whole point — removed 11 Sep 2026.
//
// This used to hard-code:
//   'Mozilla/5.0 (Windows NT 10.0; Win64; x64) … Chrome/124.0.0.0 …'
//
// which was false twice over: we run on LINUX, and the browser is Chromium 141
// here and Chrome 153 on her laptop, never 124. Worse, it was false in a way a
// site can see for itself. Chromium separately sends its own client-hint
// headers describing the real platform and version, and those are generated by
// the browser and cannot be overridden by that setting. So every request
// carried two contradictory claims about what we were:
//
//   user-agent line      → Windows, Chrome 124
//   the browser's hints  → Linux, Chromium 141
//
// A genuine browser never disagrees with itself. That contradiction is exactly
// what bot protection looks for, so the line intended to make us look ordinary
// was advertising the opposite: something hand-editing its identity.
//
// Leaving it unset means the user-agent is simply TRUE — including the fact
// that it is headless, which we are and have no business hiding. Same reasoning
// as the network bridge: the fix was to stop misrepresenting ourselves, not to
// misrepresent ourselves more convincingly.
//
// Do not re-add a hard-coded user-agent. If one is ever genuinely needed, it
// must match the browser actually running, and it has to be derived at runtime
// rather than typed in — a literal goes stale the next time Chromium updates,
// which is how this one became wrong.

