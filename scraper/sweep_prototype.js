/**
 * Every venue this script knows how to scrape, in log order — READ OFF
 * `VENUES`, never typed out.
 *
 * This was a second hand-maintained list, and it behaved exactly as a
 * duplicated list does: `frick` and `menil` were added to `VENUES` with full
 * recipes, and the run answered "Nothing matched" and named six venues,
 * because the only thing that had changed was the half nobody thought to
 * update. A recipe that exists but cannot be selected is invisible, and
 * nothing in the output says why.
 *
 * Declared here rather than at the top of the file because it reads `VENUES`,
 * which is defined above this line. Every use of it runs inside a function
 * called from main(), so the order is safe.
 *
 * Object key order in JavaScript is insertion order for string keys, so the
 * log order is the order the recipes are written in — which is the app's
 * button order (CLAUDE.md Section 7).
 */
const VENUE_ORDER = Object.keys(VENUES);

/**
 * The engine. Every venue goes through this; none has its own copy.
 */
async function scrapeVenue(page, code) {
  const v = VENUES[code];
  if (!v) { log(`  no recipe for venue "${code}"`); return []; }

  logSection(`${code.toUpperCase()} — ${v.name}`);
  const rows = [], seenUrls = new Set(), urlToRow = new Map();

  // A QUEUE, NOT A FIXED LIST, because numbered archives cannot be counted in
  // advance. See followPagination() at the bottom of this loop.
  const queue = listingPages(v);
  for (let qi = 0; qi < queue.length; qi++) {
    const pg = queue[qi];
    const url = v.base + pg.path;
    log(`  Fetching ${pg.ctx}: ${url}`);
    const r = await safeGoto(page, url, code, pg.ctx);

    // A listing page that could not be read ALWAYS leaves a marker row, for
    // every venue. This was a per-venue opt-in until 10 Sep, set only on
    // borghese and morgan — so the Met, blocked on every page, contributed
    // nothing at all to the CSV and its refusal was invisible unless someone
    // read the log. A venue that was checked and refused must say so where she
    // looks, which is the approval pile.
    if (!r.ok) {
      log(`  FAILED ${pg.ctx} — ${r.reason}`);
      rows.push({
        venue_code: code, title: `[${pg.ctx} page]`, start_date: '', end_date: '',
        summary: '', url,
        notes: `The venue's "${pg.ctx}" listing page could not be read: ${failureProse(r.reason)}. Marker row, not an exhibition.`,
      });
      continue;
    }

    // SCROLL THE LISTING BEFORE READING IT.
    //
    // The KHM builds its exhibition cards as you scroll. Read without
    // scrolling, its whole programme is TWO links — and that was reported to
    // her as "two links for an entire museum's programme", with the recipe
    // marked unresolved and the stop rule invoked. Scrolled, the same page
    // yields 20. The venue was never the problem; the reader stopped at the
    // fold, and the stop rule fired on a limit that did not exist.
    //
    // LISTING PAGES ONLY. Detail pages are read for their text, which is there
    // from the start, and there are hundreds of them — three seconds each would
    // cost far more than it could return. A listing is a handful of pages per
    // venue. It also stops as soon as the page stops growing, so a site that
    // does not lazy load pays one step rather than twelve.
    // THE BANNER COMES DOWN FIRST. A consent popin that covers the page makes
    // every later interaction a lie — see dismissConsent(), and the Louvre
    // loader that was recorded as broken because the click never landed.
    const consent = await dismissConsent(page);
    if (consent) log(`  consent banner dismissed ("${consent}")`);

    await autoScroll(page);

    // SOME LISTINGS HIDE THE REST BEHIND A BUTTON rather than behind an
    // address. Only where the venue names the control; see clickLoadMore().
    if (v.loadMore) {
      const lm = await clickLoadMore(page, v.loadMore, v.selector);
      if (lm.clicks) log(`  "load more" pressed ${lm.clicks}x on ${pg.ctx}`);
      if (lm.hitCap) {
        log(`  LOAD MORE RUNAWAY on ${pg.ctx}: still adding after 30 presses`);
        rows.push({
          venue_code: code, title: `[${pg.ctx} page]`, start_date: '', end_date: '',
          summary: '', url,
          notes: `The venue's "${pg.ctx}" listing was still revealing more exhibitions after 30 presses of its "load more" button, so reading it was stopped. Older exhibitions may be missing. Marker row, not an exhibition.`,
        });
      }
    }

    const bodyText = await page.innerText('body').catch(() => '');
    if (bodyText.length < MIN_BODY_CHARS) {
      log(`  EMPTY_PAGE ${pg.ctx}: loaded but body has <${MIN_BODY_CHARS} chars`);
      rows.push({
        venue_code: code, title: `[${pg.ctx} page]`, start_date: '', end_date: '',
        summary: '', url,
        notes: `The venue's "${pg.ctx}" listing page loaded but was empty. Marker row, not an exhibition.`,
      });
      continue;
    }

    const opts = {
      venueCode: code, ctx: pg.ctx, base: v.base, rows, seenUrls, urlToRow,
      // SOME LISTINGS MIX TEMPORARY AND PERMANENT, in named sections.
      //
      // The KHM's /en/exhibitions carries four: the great summer exhibition,
      // permanent exhibitions, special exhibitions, and permanent exhibitions
      // at the Neue Hofburg. Read whole it returns 14 rows, ten of which are
      // the museum's standing collections — Kunstkammer, Coin Cabinet, the
      // Picture Gallery. Scoped to the two sections the VENUE ITSELF labels as
      // shows, it returns the right ones.
      //
      // This is the site saying so, the same footing as excludeOngoing and
      // otherBranch, not our judgement about what a thing is.
      // Declared PER PAGE, because a venue rarely sections them all the same
      // way: the KHM's /en/exhibitions has four sections while its /upcoming
      // has none, and scoping both to the same container emptied the second.
      selector: (pg.within || v.within)
        ? (pg.within || v.within).map(w => `${w} ${v.selector}`).join(', ')
        : v.selector,
      isNav: v.isNav,
      // Every listing page this venue has, so a link back to any of them is
      // recognised as navigation whatever language prefix it carries.
      listingPaths: listingPages(v).map(p => p.path),
      excludeOngoing: !!v.excludeOngoing,
      otherBranch: v.otherBranch || null,
      excludeLabelled: v.excludeLabelled || null,
    };

    const rowsBefore = rows.length;

    try {
      const cov = await collectFromListing(page, opts);

      // A PAGE THAT LOADS AND YIELDS NOTHING MUST SAY SO TOO.
      //
      // Until now only a refusal or an empty body left a marker, so a listing
      // that served real content but produced no exhibitions vanished from the
      // CSV entirely — readable in the log and nowhere she looks. The British
      // Museum does exactly this: its current page is still served from
      // Cloudflare's edge cache, returns one link, and that link is navigation.
      // Zero rows and zero explanation, indistinguishable from a venue with
      // nothing on.
      //
      // Deliberately AFTER the de-duplication guard, so a page whose every link
      // was already collected from another of this venue's pages does not
      // report itself as empty — Tate's two "past" pages are exactly that, and
      // they are working correctly.
      //
      // ONE EXCEPTION: a page this loop DISCOVERED by following pagination.
      // An empty page is how the end of a numbered archive announces itself —
      // we ask for the page after the last one precisely to be told there is
      // nothing there. That is the mechanism working, not a venue failing, and
      // a marker row for it would appear on her approval pile on every single
      // sweep forever. A page that FAILED to load still leaves its marker
      // above, because that is a real refusal and she should see it.
      // A PAGE WHOSE LINKS WERE ALL DELIBERATELY EXCLUDED IS NOT AN EMPTY PAGE.
      //
      // The marker means "this listing gave us nothing and you should know".
      // A page whose every link was a duplicate, a permanent display, another
      // branch's show or a one-day event was read perfectly well and answered
      // the question — the answer was simply "none of these". Saying otherwise
      // puts a card on her approval pile on every sweep for a venue that is
      // working exactly as intended.
      //
      // Found the moment the Uffizi's one-day event was excluded: its upcoming
      // page holds that single item, so the page emptied and immediately
      // started claiming it could not be read.
      const excluded = cov
        ? (cov.dupUrl || 0) + (cov.ongoing || 0) + (cov.branch || 0) + (cov.labelled || 0) + (cov.offsite || 0)
        : 0;
      if (rows.length === rowsBefore && !excluded && !pg.discovered) {
        log(`  NO EXHIBITIONS ${pg.ctx}: page loaded and was read, but nothing matched`);
        rows.push({
          venue_code: code, title: `[${pg.ctx} page]`, start_date: '', end_date: '',
          summary: '', url,
          notes: `The venue's "${pg.ctx}" listing page loaded but no exhibitions could be read from it. Marker row, not an exhibition.`,
        });
      }

      followPagination(queue, pg, rows.slice(rowsBefore), rows, code, v);

    } catch (e) {
      rethrowIfAborted(e);
      log(`  ERROR extracting ${code} listing (${pg.ctx}): ${e.message.slice(0, 120)}`);
    }
  }

  // Cut before opening detail pages where the listing gave us enough to judge.
  const toFetch = v.lookbackAfterDetail ? rows : applyLookback(rows, code, 'listing');
  await fetchIndividualPages(page, toFetch, code);

  // HER RULING FOR THE MENIL, 12 Sep 2026: drop its permanent collection
  // galleries. Same decision she made for the Met's "Ongoing" label — she
  // tracks temporary exhibitions and their catalogues, and a gallery that has
  // been hung since the building opened has no closing window to buy before.
  //
  // The Met could be filtered on the word "Ongoing" because the Met prints it.
  // The Menil prints nothing: only two of its seven permanent pages say
  // "permanent collection galleries" or "ongoing" at all, so text matching
  // catches two and silently leaves five. What DOES separate them, exactly, is
  // that the Menil publishes a run for every temporary show and none for any
  // permanent gallery — verified across all 27 rows, where the seven with no
  // date are precisely the seven galleries.
  //
  // So this is opt-in per venue and NOWHERE ELSE, because generally an unknown
  // end date is never evidence about a show (the standing lookback rule), and
  // at most venues a missing date means a site that publishes badly. It runs
  // AFTER the detail pages, so a date found on the exhibition's own page
  // rescues the row, and every exclusion is named in the log.
  if (v.excludeUndated) {
    const kept = [];
    for (const r of toFetch) {
      // A ROW WHOSE OWN PAGE FAILED TO LOAD IS NEVER EXCLUDED HERE.
      //
      // The rule reads an empty pair of date columns as "the venue published no
      // run for this, so it is a permanent gallery". That inference needs the
      // page to have been READ and found to say nothing. When the page timed
      // out we know nothing at all, and the row would be dropped on the
      // strength of a network failure — invisibly, because the CSV cannot show
      // a row that is not in it. It happened on the 12 Sep verification run:
      // one of the Menil's detail pages timed out twice and its exhibition was
      // filed as a permanent display.
      //
      // Such a row is kept with the note safeGoto already wrote, which is the
      // standing rule everywhere else in the scraper: an unreadable date is
      // kept and flagged, never treated as evidence.
      if (r.detailFailed) { kept.push(r); continue; }
      if (!r.start_date && !r.end_date && !String(r.title).startsWith('[')) {
        log(`    no dates published — treated as a permanent display, excluded: ${r.title || r.url}`);
        continue;
      }
      kept.push(r);
    }
    if (kept.length !== toFetch.length) {
      log(`  ${toFetch.length - kept.length} undated row(s) excluded as permanent displays (venue rule)`);
    }
    return kept;
  }

  return toFetch;
}

/**
 * Scroll to the bottom in steps, pausing after each, so a listing that builds
 * its cards on scroll has the chance to build them. Stops early once the page
 * stops getting taller.
 */
/**
 * Get the consent banner out of the way before touching the page.
 *
 * THE LOUVRE'S "SEE MORE EXHIBITIONS" CONTROL WAS WRITTEN OFF AS BROKEN because
 * clicking it changed nothing — and it was never actually clicked. Its cookie
 * popin sits over the page and swallowed the click. Dismiss the popin first and
 * one click takes its 2025 archive from 7 links to 11, which is her count.
 *
 * That mistake is worth naming: "I clicked it and nothing happened" is only
 * evidence if the click reached the thing. The recipe carried the wrong
 * conclusion as a fact for two days.
 *
 * SCOPED TO A CONSENT CONTAINER, never the whole page. The button is only
 * pressed if it sits inside something ALWAYS_NOISE already recognises as a
 * consent manager, so this cannot wander off and press "Book tickets".
 * Refusal is preferred where a site offers it, and accept is the fallback for
 * banners that only offer that.
 */
async function dismissConsent(page, alwaysRe = ALWAYS_NOISE) {
  try {
    return await page.evaluate((reSrc) => {
      const RE = new RegExp(reSrc, 'i');
      const inConsent = (el) => {
        for (let n = el; n && n.tagName !== 'BODY' && n.tagName !== 'HTML'; n = n.parentElement) {
          const cls = typeof n.className === 'string' ? n.className : '';
          if (RE.test(cls + ' ' + (n.id || ''))) return true;
        }
        return false;
      };
      // Refuse where refusing is offered; otherwise accept. Either dismisses it.
      const words = [/reject|refuse|decline|continue without|only necessary|technical cook/i,
                     /accept|agree|tout accepter|allow/i];
      for (const w of words) {
        for (const el of document.querySelectorAll('button, a, [role="button"]')) {
          const t = (el.innerText || '').trim();
          if (!t || t.length > 80 || !w.test(t) || !inConsent(el)) continue;
          el.click();
          return t.slice(0, 60);
        }
      }
      return null;
    }, alwaysRe);
  } catch { return null; }
}

/**
 * Press a listing's "load more" control until it runs out.
 *
 * THE ADDRESS DOES NOT CHANGE, which is precisely why clicking is right here.
 * The standing rule is to check the address bar first: the Met's year menu
 * changes it, so each year is simply another page and clicking was a mistake.
 * The Louvre's loader changes nothing in the bar and has no address of its own
 * that answers — /component/load-more/expositions 404s on both the site and its
 * API host — so there is no page to fetch instead and the control IS the route.
 *
 * A venue names its own control in its recipe. There is no general rule for
 * what a "load more" button looks like, and guessing from button text across
 * five languages is exactly the sort of clever rule that has cost this project
 * before.
 *
 * Stops when the control goes away, when a press adds no links, or at the cap —
 * and the cap leaves a marker row, because reaching it means rows are missing.
 */
async function clickLoadMore(page, selector, countSelector, maxClicks = 30) {
  let clicks = 0;
  const listingUrl = page.url();
  try {
    for (; clicks < maxClicks; clicks++) {
      const count = () => page.$$eval(countSelector,
        as => new Set(as.map(a => a.getAttribute('href'))).size).catch(() => 0);
      const before = await count();
      if (!(await page.$(selector))) break;

      // THE CONTROL IS AN ANCHOR, AND ITS href IS A DEAD END.
      //
      // The Louvre's button is <a href="/component/load-more/expositions?…">,
      // an address that 404s. While the site's own handler is listening it
      // intercepts the click and loads the next batch in place. Once there is
      // nothing left to load it stops intercepting, the browser follows the
      // href, and the listing page is replaced by a 404 — which is exactly what
      // happened on the first live run: "load more pressed 1x", then ZERO links
      // on both past pages and the venue fell from 18 rows to 10.
      //
      // A single click in a probe never shows this, because the failure needs
      // the press that comes AFTER the last real one. Looping is what found it.
      //
      // So the default action is cancelled before the click, in the capture
      // phase. The site's own listener still runs — it is on the same event and
      // preventDefault does not stop other handlers — so the batch still loads;
      // only the browser's navigation is refused.
      const navigated = await page.evaluate((sel) => {
        const el = document.querySelector(sel);
        if (!el) return false;
        el.addEventListener('click', e => e.preventDefault(), { capture: true, once: true });
        el.scrollIntoView({ block: 'center' });
        el.click();
        return true;
      }, selector).catch(() => false);
      if (!navigated) break;
      await page.waitForTimeout(2500);

      // Belt and braces: if the page moved anyway, put it back and stop rather
      // than carry on reading whatever we landed on.
      if (page.url() !== listingUrl) {
        log(`    "load more" navigated away; returning to the listing`);
        await page.goto(listingUrl, { waitUntil: 'domcontentloaded', timeout: NAV_TIMEOUT }).catch(() => {});
        await page.waitForTimeout(1500);
        break;
      }

      const after = await count();
      if (after <= before) { clicks++; break; }
    }
  } catch (e) { rethrowIfAborted(e); }
  return { clicks, hitCap: clicks >= maxClicks };
}

async function autoScroll(page, maxSteps = 12) {
  try {
    let last = 0, settled = 0;
    for (let i = 0; i < maxSteps; i++) {
      await page.evaluate(() => window.scrollBy(0, window.innerHeight));
      // MEASURE AFTER THE WAIT, NOT BEFORE IT. Measuring first reads the height
      // the page had before the new cards arrived, so two steps look identical
      // and the loop stops at the fold — which is exactly how the KHM's three
      // upcoming exhibitions stayed invisible even with scrolling switched on.
      await page.waitForTimeout(450);
      const h = await page.evaluate(() => document.body.scrollHeight);
      // One unchanged step is not proof: a slow fetch can land between two
      // measurements. Stop after two in a row.
      settled = (h === last) ? settled + 1 : 0;
      if (settled >= 2) break;
      last = h;
    }
    await page.evaluate(() => window.scrollTo(0, 0));
  } catch { /* a page that will not scroll is read as it is */ }
}

async function fetchIndividualPages(page, rows, venueCode) {
  let fetched = 0, failed = 0, noText = 0;
  // Skip anything already known to have closed before the lookback floor —
  // no point spending a page load on an exhibition we will discard.
  const skip = new Set(rows.filter(r => r.end_date && !afterLookback(r.end_date, lookbackFor(venueCode))));
  if (skip.size) log(`  skipping ${skip.size} individual page(s): closed before lookback`);

  // Progress, because this is the LONGEST phase and it used to print nothing at
  // all. Borghese reads 41 pages here: two to four minutes of total silence,
  // which reads as a dead run rather than a working one — she watched it happen
  // and asked whether it had stopped. The house rule "long runs need progress"
  // was written for backgrounded commands; it applies just as much inside one.
  //
  // Every tenth page and the first, so a long venue reports without a 200-line
  // log. The count is of pages we will actually open, not of all rows.
  const due = rows.filter(r =>
    !skip.has(r) && r.url && !r.url.startsWith('[') && !(r.title || '').startsWith('['));
  if (due.length) log(`  reading ${due.length} individual page(s)…`);
  let seen = 0;

  for (const row of rows) {
    if (skip.has(row)) continue;
    // Marker rows record a listing page that failed or was empty. Their url is
    // that listing page, so without this they get fetched all over again and
    // the failure is logged twice.
    if (!row.url || row.url.startsWith('[')) continue;
    if (row.title && row.title.startsWith('[')) continue;
    seen++;
    if (seen === 1 || seen % 10 === 0) log(`    page ${seen} of ${due.length}`);
    try {
      const r = await safeGoto(page, row.url, venueCode, 'individual');
      if (!r.ok) {
        // Say which kind of failure: a dead link is the venue's own broken
        // page, not a network problem, and she can see that from the note.
        row.notes = addNote(row.notes, /^HTTP_4/.test(r.reason)
          ? `The venue's own link to this exhibition is broken (${r.reason.replace('HTTP_', 'HTTP ')}).`
          : `This exhibition's own page could not be read: ${failureProse(r.reason)}.`);
        // A PAGE WE COULD NOT READ IS NOT EVIDENCE ABOUT THE EXHIBITION.
        // Marked because excludeUndated would otherwise read this row's empty
        // date columns as the venue having published no run, and file a show
        // whose page merely timed out as a permanent display. Internal only —
        // csvRow() writes a fixed seven columns, so it never reaches the CSV.
        row.detailFailed = true;
        failed++;
        continue;
      }
      // NO NAME FROM THE LISTING? ASK THE EXHIBITION'S OWN PAGE.
      //
      // Capodimonte links half its exhibitions by image alone, with no text in
      // the link and none in the card either, and its listing carries no
      // repeat link to fill the blank from — so two real exhibitions reached
      // the CSV with an empty title and would have arrived as "Couldn't be
      // filed". Their own pages head themselves plainly: "Emilio Isgrò. Canto
      // Napoli".
      //
      // FILLS A BLANK ONLY, never overwrites. A title the listing supplied is
      // the one the venue chose for its own index and stays; this runs only
      // where the alternative is no name at all, so it cannot lose anything.
      // The page's first heading is used, not its <title> tag, which carries
      // the museum's name and section furniture.
      if (!row.title) {
        const h = await page.evaluate(() => {
          for (const el of document.querySelectorAll('h1, h2')) {
            const t = (el.innerText || '').replace(/\s+/g, ' ').trim();
            if (t.length >= 3 && t.length <= 200) return t;
          }
          return '';
        }).catch(() => '');
        if (h) {
          // THE RECIPE'S STRIPS APPLY HERE TOO. This is the third place a title
          // can come from — heading, link text, and now the exhibition's own
          // page — and the third to need saying so. The Art Institute heads its
          // pages "NOW OPEN Lee Miller: Fearless", so three rows kept badges
          // that every other row had lost, twice over across two fixes.
          const rule = titleRule(venueCode);
          let ht = h;
          if (rule.stripLeading)  ht = ht.replace(rule.stripLeading, '');
          if (rule.stripTrailing) ht = ht.replace(rule.stripTrailing, '');
          ht = squash(stripTitleNoise(ht));
          if (ht.length >= 3 && !isNotATitle(ht, rule)) {
            row.title = ht;
            row.notes = addNote(row.notes, 'Name read from the exhibition\'s own page; the listing linked it by image only.');
          }
        }
      }

      const vrec = VENUES[venueCode] || {};
      const text = await getCuratorialText(page, vrec.description, vrec.noise);
      if (text) {
        row.summary = text;
        fetched++;
      } else {
        row.notes = addNote(row.notes, 'No description could be found on this exhibition\'s own page.');
        noText++;
      }

      // Venues that print no date field at all (Borghese) write the run into
      // the opening sentence. Scan the page's text for it, using the year the
      // listing page gave us when the sentence omits one.
      // Structured data first, where the venue publishes any.
      if (!row.start_date || !row.end_date) {
        const events = await readStructuredData(page);
        const ev = pickStructuredEvent(events, row.title);
        if (ev) {
          const sd = isoDay(ev.start), ed = isoDay(ev.end);
          const filled = [];
          if (!row.start_date && sd) { row.start_date = sd; filled.push('opening'); }
          if (!row.end_date && ed)   { row.end_date   = ed; filled.push('closing'); }
          if (filled.length) {
            row.notes = addNote(row.notes,
              `${filled.join(' and ')} date taken from the site's structured data, not its visible page.`);
          }
          if (!row.summary && ev.description && ev.description.length > 60) {
            row.summary = ev.description.slice(0, 2000);
          }
        }
      }

      if (!row.start_date || !row.end_date) {
        const bodyText = await page.innerText('body').catch(() => '');
        // Borrow the year from whichever date we already hold. Venues often
        // print a bare "5 June to 25 October" on the exhibition's own page
        // while the listing card carried the year.
        //
        // Falling back to latest_year is what rescues a whole class of Borghese
        // rows. Its archive prints "March / 2024" on the listing — a real
        // published year, but no day, so NOTHING is written to the date columns
        // and both are empty here. Meanwhile the exhibition's own page says
        // "From March 26 to June 23" — real days, no year. Each half is useless
        // alone and they never met, so a fully-dated show came out blank.
        //
        // Putting them together is logic, not a guess: the venue published the
        // year for this exhibition and the days for this exhibition, and both
        // agree on the month. Her rule is that the columns stay blank where the
        // code has no applicable logic — here it has some.
        const hintYear = (row.start_date || row.end_date || '').slice(0, 4)
          || (row.latest_year ? String(row.latest_year) : '');
        const p = findDateRangeInProse(bodyText, hintYear);
        // Whether the year was borrowed rather than printed beside the days —
        // used below so the note can say so instead of implying the page stated
        // a full date.
        const yearBorrowed = !row.start_date && !row.end_date && !!row.latest_year
          && !/\d{4}/.test(p.raw || '');

        // A sentence that CONTRADICTS what the listing already told us is not
        // about this exhibition, so none of it may be used — not even the half
        // that happens to fill a gap.
        //
        // NG's exhibition pages carry a list of related events. Waldmüller's
        // page advertises a course running "7 September - 28 September 2026",
        // while the listing card says the exhibition runs "Until 20 September
        // 2026". Filling only empty fields took the course's OPENING date and
        // silently ignored its conflicting closing date — the very evidence
        // that the sentence belonged to something else.
        const clashes =
          (row.start_date && p.start && p.start !== row.start_date) ||
          (row.end_date   && p.end   && p.end   !== row.end_date);
        if (clashes) {
          log(`    prose dates ignored, they contradict the listing: "${(p.raw || '').slice(0, 70)}"`);
          p.start = ''; p.end = '';
        }

        // Fill only what is missing. If the page disagrees with the listing,
        // the listing wins — nothing already collected is silently rewritten.
        const filled = [];
        if (!row.start_date && p.start) { row.start_date = p.start; filled.push('opening'); }
        if (!row.end_date   && p.end)   { row.end_date   = p.end;   filled.push('closing'); }
        if (filled.length) {
          row.notes = addNote(row.notes,
            `${filled.join(' and ')} date read from a sentence, not a date field: "${p.raw}".`);
          // Say so when the year came from somewhere else. The sentence quoted
          // above carries no year, so without this the note reads as though the
          // page stated a full date and she has no way to see the join.
          if (yearBorrowed) {
            row.notes = addNote(row.notes,
              `The year ${hintYear} comes from the listing, which published only a month and year.`);
          }
        }

        // Still no closing date. Record what the page DOES print, if anything,
        // so the note can quote it rather than claim the page is blank.
        // Only when the page gave us NOTHING. If a date was read, quoting some
        // other fragment as what the page "shows only" contradicts the very
        // columns beside it — the Rosenquist row carried an opening date of
        // 2012-01-26 while its note claimed the page showed only "30 JUNE".
        if (!row.start_date && !row.end_date && !row._shownDateText) {
          const shown = unusableDateText(bodyText);
          if (shown) {
            row._shownDateText = shown;
            row._shownDateWhy = 'no year is published anywhere';
          }
        }
      }

      // Also try to grab dates from the individual page if we don't have them
      if (!row.start_date && !row.end_date) {
        try {
          const dateEl = await page.$('[class*="date"], [class*="Date"], time');
          if (dateEl) {
            const raw = await getText(dateEl);
            const dates = findDateRange(raw);
            if (dates.start) row.start_date = dates.start;
            if (dates.end) row.end_date = dates.end;
            if (raw && !dates.start && !dates.end) {
              row.notes = addNote(row.notes, `Date-like text could not be read: "${raw.slice(0,60)}".`);
            }
          }
        } catch {}
      }
    } catch (e) {
      rethrowIfAborted(e);
      row.notes = addNote(row.notes, `Something went wrong while reading this exhibition's own page: ${e.message.slice(0,80)}`);
      failed++;
    }
  }
  log(`  Individual pages: ${fetched} got text, ${noText} no curatorial text, ${failed} failed`);
}

// ── Deduplication ─────────────────────────────────────────────────────────────
/**
 * De-duplication is NOT this script's job, and must never be added back.
 *
 * The scraper records everything it finds. Deciding whether two rows are the
 * same exhibition happens in the app, at the Import Refresh stage, where she
 * sees each proposal and approves it. A scraper that silently drops rows it
 * judges to be duplicates is making that decision for her, unseen — and when
 * its judgement is wrong (as it was here: titles were extracted badly, so 32
 * real National Gallery exhibitions collapsed to 3 and 29 were destroyed)
 * the loss is invisible in the output.
 *
 * Duplicates in the CSV are cheap. Deleted exhibitions are not.
 *
 * This is kept as an identity function so the call site still reads clearly,
 * and so anyone reaching for "we should dedupe here" finds this note first.
 */
/**
 * Cross-reference a show that ran in more than one of a venue's own galleries.
 *
 * Acquavella lists "Portraiture: From Cassatt to Warhol" in New York and
 * "Portraiture From Cassatt to Warhol" in Palm Beach — one exhibition, two
 * runs, and normally one catalogue between them.
 *
 * Both rows are always kept. This ONLY adds a note, so the pair is
 * recognisable on the approval cards and she can accept both and dismiss one
 * in the ledger. It is not de-duplication and must never become it: a wrong
 * match here costs a misleading sentence in the notes, never a row.
 *
 * Matching ignores the location and all punctuation, so the colon that is the
 * only difference between the two spellings above does not defeat it.
 */
function noteTravellingRuns(rows, venueCode) {
  const locations = (VENUES[venueCode] && VENUES[venueCode].locations) || [];
  if (locations.length < 2) return;

  const groups = new Map();
  for (const row of rows) {
    if (!row.title) continue;
    const loc = locations.find(l => new RegExp(`\\b${l}\\b`, 'i').test(row.title));
    if (!loc) continue;
    const key = row.title
      .replace(new RegExp(`\\b${loc}\\b`, 'ig'), ' ')
      .replace(/[^\p{L}\p{N}]+/gu, ' ')
      .trim()
      .toUpperCase();
    if (!key) continue;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push({ row, loc });
  }

  for (const entries of groups.values()) {
    const locs = [...new Set(entries.map(e => e.loc))];
    if (locs.length < 2) continue;
    for (const { row, loc } of entries) {
      const others = locs.filter(l => l !== loc);
      row.notes = addNote(row.notes, `The same exhibition is also shown at ${others.join(' and ')}.`);
    }
  }
}

